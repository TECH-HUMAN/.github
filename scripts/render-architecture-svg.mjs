import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'profile', 'architecture.json');
const outputPath = path.join(repoRoot, 'profile', 'techhuman-architecture.svg');

const model = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const width = 1280;
const height = 610;
const cardWidth = 172;
const cardHeight = 188;
const startX = 58;
const gap = 30;
const cardY = 218;

const palette = {
  lime: '#d8ff57',
  cyan: '#8df6ff',
  violet: '#b8a7ff',
  emerald: '#72f0ba',
  amber: '#ffd07a'
};

function escapeXml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

function wrap(text, maxLength) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = '';

  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > maxLength && line) {
      lines.push(line);
      line = word;
    } else {
      line = next;
    }
  }

  if (line) lines.push(line);
  return lines;
}

function textBlock(lines, x, y, options = {}) {
  const {
    className = 'copy',
    lineHeight = 18,
    anchor = 'start',
    maxLines = lines.length
  } = options;

  return lines
    .slice(0, maxLines)
    .map((line, index) => {
      const suffix = index === maxLines - 1 && lines.length > maxLines ? '...' : '';
      return `<text x="${x}" y="${y + index * lineHeight}" text-anchor="${anchor}" class="${className}">${escapeXml(line + suffix)}</text>`;
    })
    .join('\n');
}

function nodeCard(node, index) {
  const x = startX + index * (cardWidth + gap);
  const accent = palette[node.accent] ?? palette.lime;
  const titleLines = wrap(node.title, 16);
  const descriptionLines = wrap(node.description, 25);
  const children = node.children ?? [];

  const childMarkup = children
    .slice(0, 4)
    .map((child, childIndex) => {
      const cy = cardY + 124 + childIndex * 19;
      return `
        <rect x="${x + 18}" y="${cy - 11}" width="${cardWidth - 36}" height="18" rx="4" class="child-bg"/>
        <circle cx="${x + 29}" cy="${cy - 2}" r="3" fill="${accent}"/>
        <text x="${x + 39}" y="${cy + 2}" class="child">${escapeXml(child)}</text>
      `;
    })
    .join('\n');

  return `
    <g class="node" transform="translate(${x}, ${cardY})">
      <rect width="${cardWidth}" height="${cardHeight}" rx="12" class="card" stroke="${accent}"/>
      <rect x="18" y="20" width="38" height="34" rx="8" fill="${accent}" fill-opacity="0.14" stroke="${accent}" stroke-opacity="0.55"/>
      <text x="37" y="43" text-anchor="middle" class="node-number" fill="${accent}">${index + 1}</text>
      <text x="18" y="76" class="eyebrow" fill="${accent}">${escapeXml(node.eyebrow)}</text>
      ${textBlock(titleLines, 18, 101, { className: 'title', lineHeight: 22, maxLines: 2 })}
      ${textBlock(descriptionLines, 18, 149, { className: 'copy', lineHeight: 17, maxLines: children.length ? 2 : 4 })}
      ${childMarkup}
    </g>
  `;
}

function connectors() {
  return model.nodes
    .slice(0, -1)
    .map((_, index) => {
      const x1 = startX + index * (cardWidth + gap) + cardWidth;
      const x2 = startX + (index + 1) * (cardWidth + gap);
      const y = cardY + 94;
      return `
        <path d="M ${x1 + 6} ${y} C ${x1 + 19} ${y}, ${x2 - 19} ${y}, ${x2 - 6} ${y}" class="connector"/>
        <circle cx="${x1 + 7}" cy="${y}" r="3" class="connector-dot"/>
        <circle cx="${x2 - 7}" cy="${y}" r="3" class="connector-dot"/>
      `;
    })
    .join('\n');
}

